CREATE TABLE LOAIHANG (
    MALOAIHANG CHAR(7) PRIMARY KEY,
    TENLOAIHANG NVARCHAR(30) NOT NULL
);

CREATE TABLE MATHANG (
    MAHANG CHAR(7) PRIMARY KEY,
    TENHANG NVARCHAR(30) NOT NULL,
    MACONGTY CHAR(7),
    MALOAIHANG CHAR(7),
    SOLUONG FLOAT,
    DONVITINH NVARCHAR(10) NOT NULL,
    GIAHANG DECIMAL(10, 2),
    FOREIGN KEY (MACONGTY) REFERENCES NHACUNGCAP(MACONGTY)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (MALOAIHANG) REFERENCES LOAIHANG(MALOAIHANG)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE NHANVIEN (
    MANHANVIEN CHAR(7) PRIMARY KEY,
    HO NVARCHAR(20) NOT NULL,
    TEN NVARCHAR(30) NOT NULL,
    NGAYSINH DATE NOT NULL,
    NGAYLAMVIEC DATE NOT NULL,
    DIACHI NVARCHAR(50) NOT NULL,
    DIENTHOAI VARCHAR(11) UNIQUE NOT NULL,
    LUONGCOBAN DECIMAL(10, 2) NOT NULL,
    PHUCAP DECIMAL(10, 2)
);

CREATE TABLE DONDATHANG (
    SOHOADON CHAR(7) PRIMARY KEY,
    MAKHACHHANG CHAR(7),
    MANHANVIEN CHAR(7),
    NGAYDATHANG DATE NOT NULL,
    NGAYGIAOHANG DATE,
    NGAYCHUYENHANG DATE,
    NOIGIAOHANG NVARCHAR(50) NOT NULL,
    FOREIGN KEY (MAKHACHHANG) REFERENCES KHACHHANG(MAKHACHHANG)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (MANHANVIEN) REFERENCES NHANVIEN(MANHANVIEN)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE CHITIETDATHANG (
    SOHOADON CHAR(7),
    MAHANG CHAR(7),
    GIABAN DECIMAL(10, 2) NOT NULL,
    SOLUONG FLOAT NOT NULL,
    MUCGIAMGIA DECIMAL(10, 2),
    PRIMARY KEY (SOHOADON, MAHANG),
    FOREIGN KEY (SOHOADON) REFERENCES DONDATHANG(SOHOADON)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (MAHANG) REFERENCES MATHANG(MAHANG)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

