CREATE PROCEDURE THONGKESOLUONGHANGBAN
    @MAHANG NVARCHAR(50) 
AS
BEGIN
    IF NOT EXISTS (SELECT 1 FROM MATHANG WHERE MAHANG = @MAHANG)
    BEGIN
        PRINT N'Loai hang nay khong ton tai';
        RETURN; 
    END

    IF NOT EXISTS (SELECT 1 FROM CHITIETDATHANG WHERE MAHANG = @MAHANG)
    BEGIN
        PRINT N'Don hang chua co nguoi mua';
        RETURN;
    END

    SELECT 
        @MAHANG AS MAHANG,
        SUM(SOLUONG) AS TONGSOLUONGBAN
