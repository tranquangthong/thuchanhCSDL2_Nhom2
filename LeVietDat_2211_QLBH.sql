CREATE TABLE NHACUNGCAP (
    MACONGTY CHAR(7) PRIMARY KEY,
    TENCONGTY NVARCHAR(50) NOT NULL,
    TENGIAODICH NVARCHAR(30),
    DIACHI NVARCHAR(50) NOT NULL,
    DIENTHOAI VARCHAR(11) UNIQUE NOT NULL,
