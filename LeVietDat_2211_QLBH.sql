IF OBJECT_ID('THEMMATHANG', 'P') IS NOT NULL
    DROP PROCEDURE THEMMATHANG;
GO

CREATE PROCEDURE THEMMATHANG
    @MaHang NVARCHAR(10),
    @TenHang NVARCHAR(100),
    @MaCongTy NVARCHAR(10),
    @MaLoaiHang NVARCHAR(10),
    @SoLuong INT,
    @DonViTinh NVARCHAR(50),
    @GiaHang FLOAT
AS
BEGIN
    IF EXISTS (SELECT 1 FROM MATHANG WHERE MAHANG = @MaHang)
    BEGIN
        PRINT 'Mã hàng đã tồn tại, không thể thêm!'
        RETURN
    END

    IF NOT EXISTS (SELECT 1 FROM NHACUNGCAP WHERE MACONGTY = @MaCongTy)
    BEGIN
        PRINT 'Mã công ty không tồn tại, không thể thêm!'
        RETURN
    END

    IF NOT EXISTS (SELECT 1 FROM LOAIHANG WHERE MALOAIHANG = @MaLoaiHang)
    BEGIN
        PRINT 'Mã loại hàng không tồn tại, không thể thêm!'
        RETURN
    END

    INSERT INTO MATHANG (MAHANG, TENHANG, MACONGTY, MALOAIHANG, SOLUONG, DONVITINH, GIAHANG)
    VALUES (@MaHang, @TenHang, @MaCongTy, @MaLoaiHang, @SoLuong, @DonViTinh, @GiaHang)

    PRINT 'Thêm mặt hàng thành công!'
END
GO
