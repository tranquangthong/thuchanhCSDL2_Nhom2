CREATE FUNCTION TONGSOLUONGHANGBANDUOC()
RETURNS TABLE
AS
RETURN
(
    SELECT 
        MH.MAHANG,
        MH.TENHANG,
        ISNULL(SUM(CTDH.SOLUONG), 0) AS TONGSOLUONGDABAN -- Nếu không có đơn hàng thì trả về 0
    FROM MATHANG MH
    LEFT JOIN CHITIETDATHANG CTDH ON MH.MAHANG = CTDH.MAHANG
    GROUP BY MH.MAHANG, MH.TENHANG
);
GO
SELECT 
    T.MAHANG,
    T.TENHANG,
    T.TONGSOLUONGDABAN,
    MH.SOLUONG AS HANGHIENCO,
    (MH.SOLUONG + T.TONGSOLUONGDABAN) AS TONGSOLUONG
FROM MATHANG MH
INNER JOIN TONGSOLUONGHANGBANDUOC() T ON MH.MaHang = T.MaHang;
